  static const List<int> _rcon = [
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36,
  ];

  static int _gfMul(int a, int b) {
    var p = 0, aa = a, bb = b;
    for (var i = 0; i < 8; i++) {
      if ((bb & 1) != 0) p ^= aa;
      final h = aa & 0x80;
      aa = (aa << 1) & 0xff;
      if (h != 0) aa ^= 0x1b;
      bb >>= 1;
    }
    return p & 0xff;
  }

  /// 密钥扩展：128bit -> 176 字节轮密钥（state 按列主序，块字节序为标准）。
  static List<int> _expandKey(List<int> key) {
    final w = List<int>.filled(_nb * (_nr + 1) * 4, 0);
    for (var i = 0; i < _nk * 4; i++) {
      w[i] = key[i];
    }
    var i = _nk;
    while (i < _nb * (_nr + 1)) {
      var temp = <int>[w[(i - 1) * 4], w[(i - 1) * 4 + 1], w[(i - 1) * 4 + 2], w[(i - 1) * 4 + 3]];
      if (i % _nk == 0) {
        // RotWord
        temp = [temp[1], temp[2], temp[3], temp[0]];
        // SubWord + Rcon
        final rconByte = _rcon[i ~/ _nk];
        temp = [
          _sbox[temp[0]] ^ rconByte,
          _sbox[temp[1]],
          _sbox[temp[2]],
          _sbox[temp[3]],
        ];
      }
      for (var k = 0; k < 4; k++) {
        w[i * 4 + k] = w[(i - _nk) * 4 + k] ^ temp[k];
      }
      i++;
    }
    return w;
  }

  /// 加密单块（16 字节）。
  static List<int> _encryptBlock(List<int> input, List<int> w) {
    // 初始化为 state（字节序=输入顺序即可，密钥扩展与 state 同序）。
    List<int> s = List<int>.from(input);
    // Round 0: AddRoundKey
    for (var i = 0; i < 16; i++) {
      s[i] ^= w[i];
    }
    for (var round = 1; round < _nr; round++) {
      // SubBytes
      for (var i = 0; i < 16; i++) {
        s[i] = _sbox[s[i]];
      }
      // ShiftRows：行号 = r，移位量为 r 字节（字节存顺序=列主序）。
      s = _shiftRows(s, left: true);
      // MixColumns
      s = _mixColumns(s);
      // AddRoundKey
      final off = round * 16;
      for (var i = 0; i < 16; i++) {
        s[i] ^= w[off + i];
      }
    }
    // Last round (no MixColumns)
    for (var i = 0; i < 16; i++) {
      s[i] = _sbox[s[i]];
    }
    s = _shiftRows(s, left: true);
    final off = _nr * 16;
    for (var i = 0; i < 16; i++) {
      s[i] ^= w[off + i];
    }
    return s;
  }

  static List<int> _decryptBlock(List<int> input, List<int> w) {
    List<int> s = List<int>.from(input);
    // 初始 AddRoundKey(w[Nr])
    var off = _nr * 16;
    for (var i = 0; i < 16; i++) {
      s[i] ^= w[off + i];
    }
    // 轮 Nr-1 .. 1：InvShiftRows → InvSubBytes → AddRoundKey → InvMixColumns
    for (var round = _nr - 1; round >= 1; round--) {
      s = _shiftRows(s, left: false);
      for (var i = 0; i < 16; i++) {
        s[i] = _invSbox[s[i]];
      }
      off = round * 16;
      for (var i = 0; i < 16; i++) {
        s[i] ^= w[off + i];
      }
      s = _invMixColumns(s);
    }
    // 末轮 InvShiftRows → InvSubBytes → AddRoundKey(w[0])
    s = _shiftRows(s, left: false);
    for (var i = 0; i < 16; i++) {
      s[i] = _invSbox[s[i]];
    }
    for (var i = 0; i < 16; i++) {
      s[i] ^= w[i];
    }
    return s;
  }

  /// ShiftRows；[left]=true 加密（左移），false 解密（右移）。
  static List<int> _shiftRows(List<int> s, {required bool left}) {
    final out = List<int>.filled(16, 0);
    for (var r = 0; r < 4; r++) {
      for (var c = 0; c < 4; c++) {
        final idx = r + 4 * c;
        final shift = left ? r : (4 - r) % 4;
        final nc = (c - shift + 4) % 4;
        out[r + 4 * nc] = s[idx];
      }
    }
    return out;
  }

  static List<int> _mixColumns(List<int> s) {
    final out = List<int>.filled(16, 0);
    for (var c = 0; c < 4; c++) {
      final i0 = c * 4, i1 = c * 4 + 1, i2 = c * 4 + 2, i3 = c * 4 + 3;
      out[i0] = _gfMul(2, s[i0]) ^ _gfMul(3, s[i1]) ^ s[i2] ^ s[i3];
      out[i1] = s[i0] ^ _gfMul(2, s[i1]) ^ _gfMul(3, s[i2]) ^ s[i3];
      out[i2] = s[i0] ^ s[i1] ^ _gfMul(2, s[i2]) ^ _gfMul(3, s[i3]);
      out[i3] = _gfMul(3, s[i0]) ^ s[i1] ^ s[i2] ^ _gfMul(2, s[i3]);
    }
    return out;
  }

  static List<int> _invMixColumns(List<int> s) {
    final out = List<int>.filled(16, 0);
    for (var c = 0; c < 4; c++) {
      final i0 = c * 4, i1 = c * 4 + 1, i2 = c * 4 + 2, i3 = c * 4 + 3;
      out[i0] = _gfMul(14, s[i0]) ^ _gfMul(11, s[i1]) ^ _gfMul(13, s[i2]) ^ _gfMul(9, s[i3]);
      out[i1] = _gfMul(9, s[i0]) ^ _gfMul(14, s[i1]) ^ _gfMul(11, s[i2]) ^ _gfMul(13, s[i3]);
      out[i2] = _gfMul(13, s[i0]) ^ _gfMul(9, s[i1]) ^ _gfMul(14, s[i2]) ^ _gfMul(11, s[i3]);
      out[i3] = _gfMul(11, s[i0]) ^ _gfMul(13, s[i1]) ^ _gfMul(9, s[i2]) ^ _gfMul(14, s[i3]);
    }
    return out;
  }

  /// 口令派生 16 字节密钥（确定性；自洽加解密无需与外部算法字节级一致）。
  static List<int> deriveKey(String password) {
    final data = password.codeUnits;
    const salt = [0x1f, 0x2d, 0x3c, 0x4a, 0x5b, 0x69, 0x78, 0x87, 0x96, 0xa5, 0xb4, 0xc3, 0xd2, 0xe1, 0xf0, 0x0f];
    final key = List<int>.from(salt);
    var h = 0x811c9dc5;
    for (final unit in data) {
      h ^= unit;
      h = (h * 0x01000193) & 0xffffffff;
      key[h & 0x0f] ^= (h >> 24) & 0xff;
      key[(h >> 4) & 0x0f] ^= (h >> 16) & 0xff;
      key[(h >> 8) & 0x0f] ^= (h >> 8) & 0xff;
    }
    return key;
  }

  /// ECB 加密 + PKCS7 填充。
  static List<int> encrypt(List<int> plain, List<int> key) {
    final w = _expandKey(key.take(16).toList());
    final padLen = 16 - (plain.length % 16);
    final padded = List<int>.from(plain)
      ..addAll(List<int>.filled(padLen, padLen));
    final out = <int>[];
    for (var i = 0; i < padded.length; i += 16) {
      out.addAll(_encryptBlock(padded.sublist(i, i + 16), w));
    }
    return out;
  }

  /// ECB 解密 + 校验 PKCS7。填充非法返回 null。
  static List<int>? decrypt(List<int> cipher, List<int> key) {
    if (cipher.isEmpty || cipher.length % 16 != 0) return null;
    final w = _expandKey(key.take(16).toList());
    final out = <int>[];
    for (var i = 0; i < cipher.length; i += 16) {
      out.addAll(_decryptBlock(cipher.sublist(i, i + 16), w));
    }
    final pad = out.last;
    if (pad < 1 || pad > 16) return null;
    for (var i = out.length - pad; i < out.length; i++) {
      if (out[i] != pad) return null;
    }
    return out.sublist(0, out.length - pad);
  }
