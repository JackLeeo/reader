  /// 简体 → 繁体。
  static String toTraditional(String text) {
    if (text.isEmpty) return text;
    final sb = StringBuffer();
    var i = 0;
    // 优先匹配词组（最长为 4）。
    while (i < text.length) {
      String? hit;
      var hitLen = 0;
      for (var len = 4; len >= 2; len--) {
        if (i + len > text.length) continue;
        final sub = text.substring(i, i + len);
        final t = _s2tPhrase[sub];
        if (t != null) {
          hit = t;
          hitLen = len;
          break;
        }
      }
      if (hit != null) {
        sb.write(hit);
        i += hitLen;
        continue;
      }
      final ch = text[i];
      sb.write(_s2t[ch] ?? ch);
      i++;
    }
    return sb.toString();
  }

